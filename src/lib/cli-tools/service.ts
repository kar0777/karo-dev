import { and, asc, eq } from 'drizzle-orm';

import { NotFoundError } from '@/lib/api/errors';
import { decryptSecret } from '@/lib/crypto/secrets';
import { db } from '@/lib/db';
import {
  cliTools,
  sandboxCliInstalls,
  userApiKeys,
  type Sandbox,
  type User,
} from '@/lib/db/schema';
